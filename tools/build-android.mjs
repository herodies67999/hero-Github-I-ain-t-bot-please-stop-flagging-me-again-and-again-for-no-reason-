import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const result = spawnSync('./gradlew', [':app:assembleRelease', '--no-daemon', '--max-workers=2', '-Pkotlin.compiler.execution.strategy=in-process'], {cwd:path.join(root,'android'), stdio:'inherit', env:process.env});
if(result.error) throw result.error;
if(result.status !== 0) process.exit(result.status || 1);
const destination = path.resolve(process.argv[2] || 'artifacts/yoru-v0.3-arm64.apk');
mkdirSync(path.dirname(destination),{recursive:true});
copyFileSync(path.join(root,'android/app/build/outputs/apk/release/app-arm64-v8a-release.apk'),destination);
console.log(destination);
